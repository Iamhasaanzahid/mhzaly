import { db, uid, save } from '../db.js';
import { icon, esc, toast, downloadFile, confirmDialog } from '../ui.js';
import { money } from '../receipt-share.js';
import { dayCloseSummary, previousClosing } from '../insights.js';
import { toCsv } from '../csv.js';

export const meta = { title: 'Day Close', subtitle: 'Cash reconciliation aur daily closing' };

function round2(n) {
  return Math.round((Number(n) || 0) * 100) / 100;
}

function todayKey() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

function varianceTone(value) {
  const n = Number(value) || 0;
  if (Math.abs(n) < 0.01) return 'ok';
  if (Math.abs(n) <= 500) return 'warn';
  return 'danger';
}

function printClosing(record) {
  const shop = esc(db.settings.shopName || 'My Mart');
  const currency = esc(db.settings.currency || 'Rs');
  const variance = Number(record.variance) || 0;
  const rows = [
    ['Opening cash', record.openingCash],
    ['Cash sales', record.cashSales],
    ['Customer cash received', record.cashIn],
    ['Cash refunds', -Math.abs(Number(record.cashRefunds) || 0)],
    ['Cash expenses', -Math.abs(Number(record.cashExpenses) || 0)],
    ['Supplier cash paid', -Math.abs(Number(record.cashOut) || 0)],
  ];
  const win = window.open('', '_blank', 'width=680,height=900');
  if (!win) return toast('Popup block ho gaya — browser allow karein', 'error');
  win.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>Day close — ${esc(record.date)}</title>
    <style>
      body{font-family:Segoe UI,system-ui,sans-serif;color:#0f172a;padding:28px;font-size:12px}
      h1{font-size:20px;margin:0 0 4px}.muted{color:#64748b;font-size:11px}
      table{width:100%;border-collapse:collapse;margin-top:16px}
      td{padding:7px 4px;border-bottom:1px solid #e2e8f0}td:last-child{text-align:right;font-weight:700}
      .box{margin-top:14px;padding:12px;border-radius:9px;background:#f8fafc;border:1px solid #e2e8f0}
      .big{font-size:18px;font-weight:800}.ok{color:#15803d}.warn{color:#b45309}.danger{color:#b91c1c}
      @media print{body{padding:0}}
    </style></head><body>
    <h1>${shop}</h1>
    <div class="muted">Day Close · ${esc(record.date)} · printed ${new Date().toLocaleString('en-GB')}</div>
    <table>${rows.map(([label, value]) => `<tr><td>${esc(label)}</td><td>${currency} ${Number(value || 0).toLocaleString()}</td></tr>`).join('')}</table>
    <div class="box"><div>Expected cash</div><div class="big">${currency} ${Number(record.expectedCash || 0).toLocaleString()}</div></div>
    <div class="box"><div>Counted cash</div><div class="big">${currency} ${Number(record.countedCash || 0).toLocaleString()}</div></div>
    <div class="box"><div>Variance</div><div class="big ${varianceTone(variance)}">${variance > 0 ? '+' : ''}${currency} ${Number(variance || 0).toLocaleString()}</div><div class="muted">${variance > 0 ? 'Cash over' : variance < 0 ? 'Cash short' : 'Perfect match'}</div></div>
    ${record.note ? `<p class="muted" style="margin-top:14px">Note: ${esc(record.note)}</p>` : ''}
    <p class="muted" style="margin-top:20px">Generated by mhzaly — offline business intelligence.</p>
    </body></html>`);
  win.document.close();
  try { win.focus(); } catch { /* ignore */ }
  setTimeout(() => { try { win.print(); } catch { /* ignore */ } }, 250);
}

export function render(root) {
  const initialDate = todayKey();
  const initialClosing = (db.closings || []).find((c) => c.date === initialDate);
  const initialOpening = initialClosing
    ? Number(initialClosing.openingCash) || 0
    : Number(previousClosing(initialDate)?.countedCash) || 0;

  root.innerHTML = `
    <div class="page-head">
      <div class="grow">
        <h2>Day Close</h2>
        <p>Din ke aakhir mein cash reconcile karein — expected cash, counted cash aur over/short record karein.</p>
      </div>
      <div class="head-actions">
        <button class="btn btn-ghost" id="dcExport">${icon('download')} Export CSV</button>
        <button class="btn btn-primary" id="dcPrint">${icon('chart')} Print summary</button>
      </div>
    </div>

    <div class="card">
      <div class="card-head">
        <h3>Close the day</h3>
        <span class="right" id="dcStatus">—</span>
      </div>
      <div class="card-pad">
        <div class="filter-row">
          <div class="field">
            <label>Business date</label>
            <input class="input" id="dcDate" type="date" value="${initialDate}" />
          </div>
          <div class="field">
            <label>Opening cash</label>
            <input class="input" id="dcOpening" type="number" step="0.01" value="${round2(initialOpening)}" />
          </div>
          <div class="field">
            <label>Cash counted</label>
            <input class="input" id="dcCounted" type="number" step="0.01" placeholder="Drawer mein cash" value="${initialClosing ? Number(initialClosing.countedCash) || 0 : ''}" />
          </div>
          <div class="field grow">
            <label>Note (optional)</label>
            <input class="input" id="dcNote" placeholder="e.g. evening shift, small change" value="${esc(initialClosing?.note || '')}" />
          </div>
        </div>

        <div class="dc-summary" id="dcSummary"></div>
        <div class="dc-reconcile" id="dcReconcile"></div>

        <div class="form-actions">
          <button class="btn btn-ghost" id="dcFill" type="button">${icon('check')} Use expected cash</button>
          <button class="btn btn-primary" id="dcSave">${icon('check')} Save closing</button>
        </div>
      </div>
    </div>

    <div class="card mt">
      <div class="card-head"><h3>Closing history</h3><span class="right" id="dcHistoryMeta">—</span></div>
      <div class="card-pad">
        <div class="table-wrap">
          <table style="width:100%">
            <thead>
              <tr>
                <th style="text-align:left">Date</th>
                <th style="text-align:right">Expected</th>
                <th style="text-align:right">Counted</th>
                <th style="text-align:right">Variance</th>
                <th style="text-align:left">Note</th>
                <th style="width:100px"></th>
              </tr>
            </thead>
            <tbody id="dcHistoryBody"></tbody>
          </table>
        </div>
      </div>
    </div>`;

  const dateEl = root.querySelector('#dcDate');
  const openingEl = root.querySelector('#dcOpening');
  const countedEl = root.querySelector('#dcCounted');
  const noteEl = root.querySelector('#dcNote');
  const statusEl = root.querySelector('#dcStatus');
  const summaryEl = root.querySelector('#dcSummary');
  const reconcileEl = root.querySelector('#dcReconcile');
  const historyBody = root.querySelector('#dcHistoryBody');
  const historyMeta = root.querySelector('#dcHistoryMeta');

  let state = {
    date: initialDate,
    existing: initialClosing || null,
    summary: null,
    expected: 0,
  };

  function paintSummary() {
    const opening = Number(openingEl.value) || 0;
    const summary = dayCloseSummary(state.date);
    const expected = opening + summary.netCash;
    const countedRaw = countedEl.value.trim();
    const counted = countedRaw === '' ? null : Number(countedRaw) || 0;
    const variance = counted == null ? null : counted - expected;
    state.summary = summary;
    state.expected = expected;

    summaryEl.innerHTML = `
      <div class="dc-stat"><span>Cash sales</span><b>${money(summary.cashSales)}</b></div>
      <div class="dc-stat"><span>Card sales</span><b>${money(summary.cardSales)}</b></div>
      <div class="dc-stat"><span>Online sales</span><b>${money(summary.onlineSales)}</b></div>
      <div class="dc-stat"><span>Udhaar sales</span><b>${money(summary.udhaarSales)}</b></div>
      <div class="dc-stat"><span>Customer cash in</span><b>${money(summary.cashIn)}</b></div>
      <div class="dc-stat"><span>Cash refunds</span><b>− ${money(summary.cashRefunds)}</b></div>
      <div class="dc-stat"><span>Cash expenses</span><b>− ${money(summary.cashExpenses)}</b></div>
      <div class="dc-stat"><span>Supplier cash out</span><b>− ${money(summary.cashOut)}</b></div>`;

    const tone = variance == null ? 'neutral' : varianceTone(variance);
    const varianceLabel = variance == null
      ? 'Cash counted enter karein'
      : Math.abs(variance) < 0.01
        ? 'Perfect match'
        : variance > 0
          ? `Over by ${money(variance)}`
          : `Short by ${money(Math.abs(variance))}`;

    reconcileEl.className = `dc-reconcile ${tone}`;
    reconcileEl.innerHTML = `
      <div class="dc-reconcile-cell">
        <span>Expected cash</span>
        <b>${money(expected)}</b>
        <em>Opening + net cash movement</em>
      </div>
      <div class="dc-reconcile-cell">
        <span>Counted cash</span>
        <b>${counted == null ? '—' : money(counted)}</b>
        <em>Drawer / galla</em>
      </div>
      <div class="dc-reconcile-cell big">
        <span>Variance</span>
        <b>${variance == null ? '—' : `${variance > 0 ? '+' : ''}${money(variance)}`}</b>
        <em>${varianceLabel}</em>
      </div>`;

    statusEl.innerHTML = state.existing
      ? `<span class="badge ok">Saved closing</span>`
      : `<span class="badge neutral">Not closed yet</span>`;

    historyBody.innerHTML = (db.closings || []).length
      ? db.closings
          .slice()
          .sort((a, b) => String(b.date).localeCompare(String(a.date)))
          .map((row) => {
            const v = Number(row.variance) || 0;
            const tone2 = varianceTone(v);
            return `<tr>
              <td><b>${esc(row.date)}</b></td>
              <td style="text-align:right">${money(row.expectedCash)}</td>
              <td style="text-align:right">${money(row.countedCash)}</td>
              <td style="text-align:right"><span class="badge ${tone2}">${v > 0 ? '+' : ''}${money(v)}</span></td>
              <td>${esc(row.note || '—')}</td>
              <td style="text-align:right; white-space:nowrap">
                <button class="btn btn-ghost btn-sm" data-close-print="${esc(row.id)}" title="Print">${icon('chart')}</button>
                <button class="btn btn-ghost btn-sm" data-close-del="${esc(row.id)}" title="Delete">${icon('trash')}</button>
              </td>
            </tr>`;
          })
          .join('')
      : '<tr><td colspan="6"><div class="empty-state">Abhi koi day close save nahi hua.</div></td></tr>';

    historyMeta.textContent = `${(db.closings || []).length} closing(s)`;
  }

  function loadDate(date) {
    state.date = date;
    state.existing = (db.closings || []).find((c) => c.date === date) || null;
    const prev = previousClosing(date);
    openingEl.value = state.existing
      ? Number(state.existing.openingCash) || 0
      : Number(prev?.countedCash) || 0;
    countedEl.value = state.existing ? Number(state.existing.countedCash) || 0 : '';
    noteEl.value = state.existing?.note || '';
    paintSummary();
  }

  dateEl.addEventListener('change', () => loadDate(dateEl.value || todayKey()));
  openingEl.addEventListener('input', paintSummary);
  countedEl.addEventListener('input', paintSummary);

  root.querySelector('#dcFill').addEventListener('click', () => {
    countedEl.value = round2(state.expected);
    paintSummary();
  });

  root.querySelector('#dcSave').addEventListener('click', () => {
    if (countedEl.value.trim() === '') {
      countedEl.focus();
      return toast('Cash counted enter karein', 'error');
    }
    const counted = Number(countedEl.value) || 0;
    const opening = Number(openingEl.value) || 0;
    const summary = state.summary || dayCloseSummary(state.date);
    const expected = opening + summary.netCash;
    const record = {
      id: state.existing?.id || uid('close'),
      date: state.date,
      openingCash: round2(opening),
      expectedCash: round2(expected),
      countedCash: round2(counted),
      variance: round2(counted - expected),
      cashSales: round2(summary.cashSales),
      cardSales: round2(summary.cardSales),
      onlineSales: round2(summary.onlineSales),
      udhaarSales: round2(summary.udhaarSales),
      cashRefunds: round2(summary.cashRefunds),
      cashExpenses: round2(summary.cashExpenses),
      cashIn: round2(summary.cashIn),
      cashOut: round2(summary.cashOut),
      netCash: round2(summary.netCash),
      invoices: summary.invoices,
      note: noteEl.value.trim(),
      closedAt: new Date().toISOString(),
    };
    if (state.existing) {
      Object.assign(state.existing, record);
    } else {
      db.closings = db.closings || [];
      db.closings.push(record);
    }
    save();
    state.existing = record;
    paintSummary();
    toast(`Day close saved — ${record.variance === 0 ? 'perfect match' : record.variance > 0 ? 'cash over' : 'cash short'}`, record.variance === 0 ? 'success' : 'error');
  });

  root.querySelector('#dcPrint').addEventListener('click', () => {
    const record = state.existing || {
      date: state.date,
      openingCash: Number(openingEl.value) || 0,
      expectedCash: state.expected,
      countedCash: Number(countedEl.value) || 0,
      variance: (Number(countedEl.value) || 0) - state.expected,
      cashSales: state.summary?.cashSales || 0,
      cashIn: state.summary?.cashIn || 0,
      cashRefunds: state.summary?.cashRefunds || 0,
      cashExpenses: state.summary?.cashExpenses || 0,
      cashOut: state.summary?.cashOut || 0,
      note: noteEl.value.trim(),
    };
    printClosing(record);
  });

  root.querySelector('#dcExport').addEventListener('click', () => {
    const rows = [['Date', 'Opening', 'Expected', 'Counted', 'Variance', 'Cash sales', 'Cash in', 'Cash refunds', 'Cash expenses', 'Supplier cash out', 'Invoices', 'Note', 'Closed at']];
    for (const c of (db.closings || []).slice().sort((a, b) => String(a.date).localeCompare(String(b.date)))) {
      rows.push([
        c.date, round2(c.openingCash), round2(c.expectedCash), round2(c.countedCash), round2(c.variance),
        round2(c.cashSales), round2(c.cashIn), round2(c.cashRefunds), round2(c.cashExpenses), round2(c.cashOut),
        c.invoices || 0, c.note || '', c.closedAt || '',
      ]);
    }
    downloadFile(`mhzaly-day-close-${new Date().toISOString().slice(0, 10)}.csv`, toCsv(rows), 'text/csv');
    toast('Day close history exported', 'success');
  });

  historyBody.addEventListener('click', (e) => {
    const printBtn = e.target.closest('[data-close-print]');
    if (printBtn) {
      const record = (db.closings || []).find((c) => c.id === printBtn.dataset.closePrint);
      if (record) printClosing(record);
      return;
    }
    const delBtn = e.target.closest('[data-close-del]');
    if (delBtn) {
      const record = (db.closings || []).find((c) => c.id === delBtn.dataset.closeDel);
      if (!record) return;
      confirmDialog(`Closing ${record.date} delete karein?`, () => {
        db.closings = db.closings.filter((c) => c.id !== record.id);
        save();
        if (state.date === record.date) loadDate(record.date);
        else paintSummary();
        toast('Closing deleted', 'success');
      });
    }
  });

  paintSummary();
}
