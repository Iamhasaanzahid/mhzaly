import { db, save } from '../db.js';
import { icon, esc, toast, downloadFile } from '../ui.js';
import { money } from '../receipt-share.js';
import { restockPlan } from '../insights.js';
import { toCsv } from '../csv.js';

export const meta = { title: 'Smart Restock', subtitle: 'Demand forecast aur purchase plan' };

const STATUS = {
  out: { label: 'Out of stock', tone: 'danger' },
  low: { label: 'Low stock', tone: 'warn' },
  urgent: { label: 'Reorder soon', tone: 'warn' },
  dead: { label: 'No sales', tone: 'neutral' },
  ok: { label: 'Healthy', tone: 'ok' },
};

function coverText(cover) {
  if (cover == null) return '—';
  if (!Number.isFinite(cover)) return '—';
  if (cover < 1) return '<1d';
  return `${Math.round(cover)}d`;
}

function buildPlan(root) {
  return restockPlan({
    days: Number(root.querySelector('#restockRange').value) || 30,
    leadDays: Number(root.querySelector('#restockLead').value) || 0,
    coverDays: Number(root.querySelector('#restockCover').value) || 14,
  });
}

function filteredRows(plan, filter) {
  if (filter === 'reorder') return plan.reorder;
  if (filter === 'urgent') return plan.rows.filter((row) => ['out', 'low', 'urgent'].includes(row.status));
  if (filter === 'dead') return plan.rows.filter((row) => row.status === 'dead');
  return plan.rows;
}

function planText(plan, rows) {
  const shop = db.settings.shopName || 'My Mart';
  const lines = [
    `mhzaly Smart Restock — ${shop}`,
    `Sales window: ${plan.days} din · Lead time: ${plan.leadDays} din · Cover: ${plan.coverDays} din`,
    '',
  ];
  if (!rows.length) {
    lines.push('Koi restock item nahi — stock theek hai.');
  } else {
    rows.forEach((row, i) => {
      lines.push(`${i + 1}. ${row.product.name} — order ${row.suggested} ${row.product.unit || 'pcs'} (approx ${money(row.cost)})`);
    });
    lines.push('');
    lines.push(`Total units: ${plan.totals.units} · Estimated cost: ${money(plan.totals.cost)}`);
  }
  lines.push('', 'Generated by mhzaly · offline business intelligence');
  return lines.join('\n');
}

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    toast('Restock list copy ho gayi', 'success');
  } catch {
    const area = document.createElement('textarea');
    area.value = text;
    area.style.position = 'fixed';
    area.style.opacity = '0';
    document.body.appendChild(area);
    area.select();
    try {
      document.execCommand('copy');
      toast('Restock list copy ho gayi', 'success');
    } catch {
      toast('Copy nahi ho saka', 'error');
    }
    area.remove();
  }
}

function printPlan(plan, rows) {
  const shop = esc(db.settings.shopName || 'My Mart');
  const currency = esc(db.settings.currency || 'Rs');
  const body = rows.length
    ? rows.map((row) => `<tr>
        <td>${esc(row.product.name)}</td>
        <td style="text-align:right">${row.stock}</td>
        <td style="text-align:right">${row.sold}</td>
        <td style="text-align:right">${row.suggested}</td>
        <td style="text-align:right">${currency} ${Number(row.cost || 0).toLocaleString()}</td>
      </tr>`).join('')
    : '<tr><td colspan="5" style="text-align:center;color:#64748b">Koi restock item nahi.</td></tr>';

  const win = window.open('', '_blank', 'width=760,height=900');
  if (!win) return toast('Popup block ho gaya — browser allow karein', 'error');
  win.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>Restock plan — ${shop}</title>
    <style>
      body{font-family:Segoe UI,system-ui,sans-serif;color:#0f172a;padding:28px;font-size:12px}
      h1{font-size:20px;margin:0 0 4px} .muted{color:#64748b;font-size:11px}
      table{width:100%;border-collapse:collapse;margin-top:16px}
      th,td{border-bottom:1px solid #e2e8f0;padding:8px 6px;text-align:left}
      th{font-size:10px;text-transform:uppercase;letter-spacing:.05em;color:#64748b}
      .total{margin-top:14px;padding:10px 12px;background:#f0fdfa;border:1px solid #99f6e4;border-radius:8px;font-weight:700}
      @media print{body{padding:0}}
    </style></head><body>
    <h1>${shop}</h1>
    <div class="muted">Smart Restock plan · ${plan.days} din sales · Lead ${plan.leadDays}d · Cover ${plan.coverDays}d · ${new Date().toLocaleString('en-GB')}</div>
    <table><thead><tr><th>Product</th><th style="text-align:right">Stock</th><th style="text-align:right">Sold</th><th style="text-align:right">Order</th><th style="text-align:right">Est. cost</th></tr></thead><tbody>${body}</tbody></table>
    <div class="total">Total units: ${plan.totals.units} · Estimated purchase: ${currency} ${Number(plan.totals.cost || 0).toLocaleString()}</div>
    <p class="muted" style="margin-top:18px">Generated by mhzaly — offline business intelligence.</p>
    </body></html>`);
  win.document.close();
  try { win.focus(); } catch { /* ignore */ }
  setTimeout(() => { try { win.print(); } catch { /* ignore */ } }, 250);
}

